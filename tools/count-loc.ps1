# Counts the lines of code of Topaz and rewrites codestats.h, which the About dialog shows
# (TOPAZ tab: "LINES OF CODE"). Run once per release, before the Release build:
#   powershell -ExecutionPolicy Bypass -File tools\count-loc.ps1
#
# Counted: non-blank lines of every file git knows about (tracked + new, not ignored), by
#   - Topaz code:   *.cpp *.h *.qml *.py *.ps1 *.sh *.iss *.cmake *.rc, CMakeLists.txt,
#                   Dockerfile.linux -- everything outside third_party/
#   - 3rd party:    the libraries vendored as source and compiled into Topaz itself
#                   (third_party/: KISS FFT, miniz). projectM, GLEW, Qt, FFmpeg and BASS
#                   are separate libraries and not counted.
# Not counted: docs (*.md), images, SVG icons, JSON, codestats.h itself.

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Push-Location $root
try {
    $files = git ls-files -c -o --exclude-standard
    if ($LASTEXITCODE -ne 0) { throw 'git ls-files failed' }
} finally { Pop-Location }

$codeExt = '.cpp', '.h', '.c', '.qml', '.py', '.ps1', '.sh', '.iss', '.cmake', '.rc'
$codeNames = 'CMakeLists.txt', 'Dockerfile.linux'

$topaz = 0; $third = 0; $topazFiles = 0; $thirdFiles = 0
foreach ($f in $files | Sort-Object -Unique) {
    if ($f -eq 'codestats.h') { continue }
    $name = Split-Path $f -Leaf
    $ext  = [IO.Path]::GetExtension($f).ToLowerInvariant()
    if (-not (($codeExt -contains $ext) -or ($codeNames -contains $name))) { continue }
    $path = Join-Path $root $f
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { continue }
    $n = @([IO.File]::ReadAllLines($path) | Where-Object { $_.Trim() -ne '' }).Count
    if ($f -like 'third_party/*') { $third += $n; $thirdFiles++ } else { $topaz += $n; $topazFiles++ }
}

$date = Get-Date -Format 'yyyy-MM-dd'
$header = @"
// Generated by tools/count-loc.ps1 on $date -- do not edit by hand; rerun it once per release.
// Non-blank lines of code, shown in the About dialog (BuildInfo::topazLines / thirdPartyLines).
#pragma once

#define TOPAZ_CODE_LINES        $topaz   // $topazFiles files: C++, QML, CMake, scripts
#define TOPAZ_THIRD_PARTY_LINES $third   // $thirdFiles files: KISS FFT + miniz (third_party/)
"@
[IO.File]::WriteAllText((Join-Path $root 'codestats.h'), $header.Replace("`r`n", "`n") + "`n")
Write-Host "Topaz code:     $topaz lines in $topazFiles files"
Write-Host "3rd-party code: $third lines in $thirdFiles files (KISS FFT, miniz)"
