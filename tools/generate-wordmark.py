"""Generates Topaz_Wordmark_Topaz.svg + Topaz_Wordmark_Jukebox.svg -- the neon
"TOPAZ JUKEBOX" lettering in TopBar.qml (one file per word, see write() below).

The letters are converted to outlines (no <text>), so the SVG needs no font
and renders identically on Windows and Linux. Only SVG Tiny 1.2 features that
Qt's QtSvg renderer supports are used: paths, userSpaceOnUse linear gradients,
fill opacity, transforms -- no filters (blur/glow would be silently ignored).

Font: Monoton by Vernon Adams (SIL Open Font License 1.1), downloaded from the
google/fonts repository at run time; only the glyph outlines end up in the SVG.

Run from the repo root (Git Bash, Docker Desktop running):

  MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W):/src" -w /src python:3.12-slim \
    bash -c "pip install -q fonttools uharfbuzz && python tools/generate-wordmark.py"

Optional preview PNG (same container, before python): apt-get install librsvg2-bin,
then: rsvg-convert -b '#131313' -z 4 Topaz_Wordmark_Topaz.svg -o /tmp/preview.png
The neon glow is NOT in the SVGs (Qt's SVG renderer ignores filters): TopBar.qml
adds it with a MultiEffect per word.
"""
import os
import tempfile
import urllib.request

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT_URL = "https://github.com/google/fonts/raw/main/ofl/monoton/Monoton-Regular.ttf"
OUT_TOPAZ = "Topaz_Wordmark_Topaz.svg"
OUT_JUKEBOX = "Topaz_Wordmark_Jukebox.svg"

PAD = 6             # transparent margin around the letters (px)
SIZE = 40           # "TOPAZ" font size (px); "JUKEBOX" is 62 % of it
GAP = 10            # space between the two words (px)
SHADOW = 2.0        # hard drop shadow offset (px, down-right)

# Neon colours, top -> bottom of the cap height
PINK = [(0, "#FFD1F0"), (0.5, "#FF4FB8"), (1, "#B03BFF")]   # TOPAZ
CYAN = [(0, "#D9FFFF"), (0.5, "#3BE8FF"), (1, "#2B8CFF")]   # JUKEBOX

font_path = os.path.join(tempfile.gettempdir(), "Monoton-Regular.ttf")
if not os.path.exists(font_path):
    urllib.request.urlretrieve(FONT_URL, font_path)

tt = TTFont(font_path)
glyph_set = tt.getGlyphSet()
glyph_order = tt.getGlyphOrder()
face = hb.Face(hb.Blob.from_file_path(font_path))
hb_font = hb.Font(face)
upem = face.upem
cap_height = getattr(tt["OS/2"], "sCapHeight", 0) or int(upem * 0.7)


def shape(text, size, x0, baseline, tracking_em):
    """Outlines of `text` (kerned by HarfBuzz) as one SVG path; returns (d, end_x)."""
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hb_font, buf, {"kern": True, "liga": True})
    s = size / upem
    x, parts = x0, []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        pen = SVGPathPen(glyph_set)
        glyph_set[glyph_order[info.codepoint]].draw(
            TransformPen(pen, (s, 0, 0, -s, x + pos.x_offset * s, baseline - pos.y_offset * s)))
        parts.append(pen.getCommands())
        x += pos.x_advance * s + tracking_em * size
    return " ".join(parts), x - tracking_em * size


def gradient(gid, y1, y2, stops):
    st = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops)
    return (f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" '
            f'x1="0" y1="{y1:.1f}" x2="0" y2="{y2:.1f}">{st}</linearGradient>')


cap = cap_height * SIZE / upem
baseline = PAD + cap                       # tight frame: caps start at PAD
d1, x1 = shape("TOPAZ", SIZE, PAD, baseline, 0.02)
d2, x2 = shape("JUKEBOX", SIZE * 0.62, x1 + GAP, baseline, 0.04)
cap2 = cap * 0.62

width = x2 + PAD + SHADOW
height = baseline + PAD + SHADOW
split = x1 + GAP / 2                       # where the TOPAZ file ends and JUKEBOX begins


def write(path, vb_x, vb_w, defs, body):
    """Both files share one coordinate system and height; each viewBox covers
    only its own word, so the two Images placed side by side (TopBar.qml)
    reproduce the combined lettering exactly."""
    with open(path, "w", newline="\n") as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" version="1.2" baseProfile="tiny" '
                f'width="{vb_w:.1f}" height="{height:.1f}" '
                f'viewBox="{vb_x:.1f} 0 {vb_w:.1f} {height:.1f}">'
                # (no double hyphen inside an XML comment: it makes the file invalid)
                f'<!-- Generated by tools/generate-wordmark.py; edit the script, not this file. '
                f'Lettering: Monoton by Vernon Adams, SIL Open Font License 1.1 -->'
                f'<defs>{defs}</defs>{body}</svg>\n')
    print(f"{path}: {vb_w:.1f} x {height:.1f}")


# Two files (not one) so TopBar can give each word its own MultiEffect glow colour.
write(OUT_TOPAZ, 0, split,
      gradient("pink", baseline - cap, baseline, PINK),
      f'<path d="{d1}" transform="translate({SHADOW},{SHADOW})" fill="#000000" fill-opacity="0.6"/>'
      f'<path d="{d1}" fill="url(#pink)"/>')
write(OUT_JUKEBOX, split, width - split,
      gradient("cyan", baseline - cap2, baseline, CYAN),
      f'<path d="{d2}" transform="translate({SHADOW * 0.8},{SHADOW * 0.8})" fill="#000000" fill-opacity="0.6"/>'
      f'<path d="{d2}" fill="url(#cyan)"/>')
